        private void SetSessionCookie(string sessionId)
        {
            var cookieOptions = new CookieOptions
            {
                HttpOnly = true,
                Secure = Request.IsHttps,
                SameSite = SameSiteMode.Lax,
                Path = "/",
                Expires = DateTimeOffset.UtcNow.AddHours(8)
            };
            Response.Cookies.Append(RedisSessionAuthenticationHandler.CookieName, sessionId, cookieOptions);
        }

        private void ClearSessionCookie()
        {
            Response.Cookies.Delete(RedisSessionAuthenticationHandler.CookieName, new CookieOptions
            {
                Path = "/",
                HttpOnly = true,
                Secure = Request.IsHttps,
                SameSite = SameSiteMode.Lax
            });
        }

        [HttpPost("register")]
        public async Task<ActionResult<AuthResponse>> Register(RegisterRequest request)
        {
            try
            {
                // Validate required fields
                if (string.IsNullOrWhiteSpace(request.Name) || 
                    string.IsNullOrWhiteSpace(request.Email) || 
                    string.IsNullOrWhiteSpace(request.ProfileImage))
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Name, email, and profile image are required"
                    });
                }

                // Check if user already exists
                if (_context.Users.Any(u => u.Email == request.Email && u.UniversityId==request.UniversityId))
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "User already exists"
                    });
                }

                // Check if there is an active, unused invitation for this email and university
                var invitation = await _context.Invitations
                    .FirstOrDefaultAsync(i => i.Email.ToLower() == request.Email.Trim().ToLower() 
                                           && i.UniversityId == request.UniversityId 
                                           && !i.IsUsed 
                                           && i.ExpiresAt >= DateTime.UtcNow);

                string finalUserType = request.UserType;
                bool isActive = false;
                bool isApproved = false;

                if (invitation != null)
                {
                    finalUserType = invitation.UserType;
                    isActive = true;
                    isApproved = true;
                    invitation.IsUsed = true;
                }

                string autoGeneratedPassword = "";
                string passwordHash = "";

                if (isApproved)
                {
                    autoGeneratedPassword = _passwordGenerationService.GeneratePassword();
                    var passwordToHash = !string.IsNullOrWhiteSpace(request.Password) ? request.Password : autoGeneratedPassword;
                    passwordHash = HashPassword(passwordToHash);
                }
                else if (!string.IsNullOrWhiteSpace(request.Password))
                {
                    passwordHash = HashPassword(request.Password);
                }

                // Create new user
                var user = new User
                {
                    Name = request.Name,
                    Email = request.Email,
                    PasswordHash = passwordHash,
                    AutoGeneratedPassword = autoGeneratedPassword,
                    UserType = finalUserType,
                    UniversityId = request.UniversityId,
                    SubjectId1 = request.SubjectId1,
                    SubjectId2 = request.SubjectId2,
                    SubjectId3 = request.SubjectId3,
                    EmpId = request.EmpId,
                    Fname = request.Fname ?? "",
                    AadharNo = request.AadharNo ?? "",
                    PanNo = request.PanNo ?? "",
                    CollegeId = request.CollegeId,
                    Experience = request.Experience ?? "",
                    Phone = request.Phone ?? "",
                    Address = request.Address ?? "",
                    ProfileImage = request.ProfileImage ?? "",
                    IsActive = isActive,
                    IsApproved = isApproved
                };

                _context.Users.Add(user);
                await _context.SaveChangesAsync();

                // Send auto-generated password email only if approved
                if (isApproved && !string.IsNullOrEmpty(autoGeneratedPassword))
                {
                    try
                    {
                        await _emailService.SendAutoGeneratedPasswordAsync(user.Email, user.Name, autoGeneratedPassword);
                    }
                    catch (Exception ex)
                    {
                        // Log the error but don't fail the registration
                        Console.WriteLine($"Failed to send email: {ex.Message}");
                    }
                }

                var sessionId = Convert.ToHexString(RandomNumberGenerator.GetBytes(32));
                var permissions = await _permissionService.GetRolePermissionsAsync(user.UserType);

                var userDto = new UserDto
                {
                    Id = user.Id,
                    Name = user.Name,
                    Email = user.Email,
                    UserType = user.UserType,
                    UniversityId = user.UniversityId,
                    SubjectId1 = user.SubjectId1,
                    SubjectId2 = user.SubjectId2,
                    SubjectId3 = user.SubjectId3,
                    EmpId = user.EmpId,
                    Fname = user.Fname,
                    AadharNo = user.AadharNo,
                    PanNo = user.PanNo,
                    CollegeId = user.CollegeId,
                    Experience = user.Experience,
                    Phone = user.Phone,
                    Address = user.Address,
                    ProfileImage = user.ProfileImage,
                    IsActive = user.IsActive,
                    IsApproved = user.IsApproved,
                    UniversityName = user.University?.UniversityName,
                    Permissions = permissions
                };

                if (user.IsActive)
                {
                    var sessionData = new UserSessionData
                    {
                        Id = user.Id,
                        Name = user.Name,
                        Email = user.Email,
                        UserType = user.UserType,
                        UniversityId = user.UniversityId,
                        SubjectId1 = user.SubjectId1,
                        CollegeId = user.CollegeId,
                        Permissions = permissions
                    };

                    try
                    {
                        var cacheOptions = new DistributedCacheEntryOptions
                        {
                            AbsoluteExpirationRelativeToNow = TimeSpan.FromHours(8)
                        };
                        await _cache.SetStringAsync($"session:{sessionId}", JsonSerializer.Serialize(sessionData, _jsonOptions), cacheOptions);
                        await _cache.SetStringAsync($"user_details_{user.Id}", JsonSerializer.Serialize(userDto, _jsonOptions), cacheOptions);
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"[Redis Cache] Error caching session on register: {ex.Message}");
                    }

                    SetSessionCookie(sessionId);
                }

                return Ok(new AuthResponse
                {
                    Success = true,
                    Message = user.IsActive 
                        ? "User registered successfully" 
                        : "Registration successful! Your account is pending approval by the coordinator.",
                    Token = sessionId,
                    User = userDto
                });
            }
            catch (Exception ex)
            {
                var msg = ex.Message;
                if (ex.InnerException != null)
                {
                    msg += " | InnerException: " + ex.InnerException.Message;
                }
                return StatusCode(500, new AuthResponse
                {
                    Success = false,
                    Message = msg
                });
            }
        }

