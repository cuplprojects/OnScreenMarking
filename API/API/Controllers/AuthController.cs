        private void SetSessionCookie(string sessionId)
        {
            var cookieOptions = new CookieOptions
            {
                HttpOnly = true,
                Secure = Request.IsHttps,
                SameSite = SameSiteMode.Lax,
                Path = "/",
                Expires = DateTimeOffset.UtcNow.AddHours(8)
            };
            Response.Cookies.Append(RedisSessionAuthenticationHandler.CookieName, sessionId, cookieOptions);
        }

        private void ClearSessionCookie()
        {
            Response.Cookies.Delete(RedisSessionAuthenticationHandler.CookieName, new CookieOptions
            {
                Path = "/",
                HttpOnly = true,
                Secure = Request.IsHttps,
                SameSite = SameSiteMode.Lax
            });
        }

        [HttpPost("register")]
        public async Task<ActionResult<AuthResponse>> Register(RegisterRequest request)
        {
            try
            {
                // Validate required fields
                if (string.IsNullOrWhiteSpace(request.Name) || 
                    string.IsNullOrWhiteSpace(request.Email) || 
                    string.IsNullOrWhiteSpace(request.ProfileImage))
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Name, email, and profile image are required"
                    });
                }

                string finalUserType = "examiner"; // Default & only allowed role for public self-registration
                int finalUniversityId;
                bool isActive = false;
                bool isApproved = false;
                string autoGeneratedPassword = "";
                string passwordHash = "";

                // Check if claiming an invited account via invitation token
                if (!string.IsNullOrWhiteSpace(request.InvitationToken))
                {
                    var invitation = await _context.Invitations
                        .FirstOrDefaultAsync(i => i.Token == request.InvitationToken.Trim());

                    if (invitation == null || invitation.IsUsed || invitation.ExpiresAt < DateTime.UtcNow)
                    {
                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "Invalid, used, or expired invitation token."
                        });
                    }

                    if (string.Compare(invitation.Email.Trim(), request.Email.Trim(), StringComparison.OrdinalIgnoreCase) != 0)
                    {
                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "Invitation token does not match the provided email address."
                        });
                    }

                    // Check if user already exists
                    if (await _context.Users.AnyAsync(u => u.Email == invitation.Email && u.UniversityId == invitation.UniversityId))
                    {
                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "A user with this email address is already registered."
                        });
                    }

                    // Ignore client-supplied UserType and UniversityId; enforce from verified invitation
                    finalUserType = invitation.UserType;
                    finalUniversityId = invitation.UniversityId;
                    isActive = true;
                    isApproved = true;
                    invitation.IsUsed = true;

                    // Generate a strong random password and send via email; do not accept arbitrary client password
                    autoGeneratedPassword = _passwordGenerationService.GeneratePassword();
                    passwordHash = _passwordHasher.HashPassword(autoGeneratedPassword);
                }
                else
                {
                    // Public self-registration without invitation
                    // 1. Validate university exists
                    if (!request.UniversityId.HasValue || !await _context.Universities.AnyAsync(u => u.UniversityId == request.UniversityId.Value))
                    {
                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "A valid university selection is required."
                        });
                    }

                    finalUniversityId = request.UniversityId.Value;

                    // 2. Role whitelist: public applicants can NEVER self-select admin or coordinator
                    finalUserType = "examiner";

                    // 3. Check if user already exists
                    if (await _context.Users.AnyAsync(u => u.Email.ToLower() == request.Email.Trim().ToLower() && u.UniversityId == finalUniversityId))
                    {
                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "A user with this email is already registered at this university."
                        });
                    }

                    // 4. Public registrations are pending approval; do not accept client passwords for unapproved accounts
                    isActive = false;
                    isApproved = false;
                    passwordHash = "";
                    autoGeneratedPassword = "";
                }

                // Create new user (never persist plaintext passwords in AutoGeneratedPassword column)
                var user = new User
                {
                    Name = request.Name.Trim(),
                    Email = request.Email.Trim().ToLower(),
                    PasswordHash = passwordHash,
                    AutoGeneratedPassword = "", // Do not store plaintext password in database
                    UserType = finalUserType,
                    UniversityId = finalUniversityId,
                    SubjectId1 = request.SubjectId1,
                    SubjectId2 = request.SubjectId2,
                    SubjectId3 = request.SubjectId3,
                    EmpId = request.EmpId,
                    Fname = request.Fname ?? "",
                    AadharNo = request.AadharNo ?? "",
                    PanNo = request.PanNo ?? "",
                    CollegeId = request.CollegeId,
                    Experience = request.Experience ?? "",
                    Phone = request.Phone ?? "",
                    Address = request.Address ?? "",
                    ProfileImage = request.ProfileImage ?? "",
                    IsActive = isActive,
                    IsApproved = isApproved
                };

                _context.Users.Add(user);
                await _context.SaveChangesAsync();

                // Send auto-generated password email only if approved via verified invitation
                if (isApproved && !string.IsNullOrEmpty(autoGeneratedPassword))
                {
                    try
                    {
                        await _emailService.SendAutoGeneratedPasswordAsync(user.Email, user.Name, autoGeneratedPassword);
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"Failed to send credentials email: {ex.Message}");
                    }
                }

                var sessionId = "";
                var permissions = await _permissionService.GetRolePermissionsAsync(user.UserType);

                var userDto = new UserDto
                {
                    Id = user.Id,
                    Name = user.Name,
                    Email = user.Email,
                    UserType = user.UserType,
                    UniversityId = user.UniversityId,
                    SubjectId1 = user.SubjectId1,
                    SubjectId2 = user.SubjectId2,
                    SubjectId3 = user.SubjectId3,
                    EmpId = user.EmpId,
                    Fname = user.Fname,
                    AadharNo = user.AadharNo,
                    PanNo = user.PanNo,
                    CollegeId = user.CollegeId,
                    Experience = user.Experience,
                    Phone = user.Phone,
                    Address = user.Address,
                    ProfileImage = user.ProfileImage,
                    IsActive = user.IsActive,
                    IsApproved = user.IsApproved,
                    UniversityName = user.University?.UniversityName,
                    Permissions = permissions
                };

                if (user.IsActive)
                {
                    sessionId = Convert.ToHexString(RandomNumberGenerator.GetBytes(32));
                    var sessionData = new UserSessionData
                    {
                        Id = user.Id,
                        Name = user.Name,
                        Email = user.Email,
                        UserType = user.UserType,
                        UniversityId = user.UniversityId,
                        SubjectId1 = user.SubjectId1,
                        CollegeId = user.CollegeId,
                        Permissions = permissions
                    };

                    try
                    {
                        var cacheOptions = new DistributedCacheEntryOptions
                        {
                            AbsoluteExpirationRelativeToNow = TimeSpan.FromHours(8)
                        };
                        await _cache.SetStringAsync($"session:{sessionId}", JsonSerializer.Serialize(sessionData, _jsonOptions), cacheOptions);
                        await _cache.SetStringAsync($"user_details_{user.Id}", JsonSerializer.Serialize(userDto, _jsonOptions), cacheOptions);
                        SetSessionCookie(sessionId);
                    }
                    catch (Exception ex)
                    {
                        _logger.LogError(ex, "Error caching session on register");
                        sessionId = "";
                    }
                }

                return Ok(new AuthResponse
                {
                    Success = true,
                    Message = user.IsActive 
                        ? "User registered successfully" 
                        : "Registration successful! Your application has been submitted and is pending administrative approval by your university coordinator.",
                    Token = sessionId,
                    User = userDto
                });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error processing Register");
                return StatusCode(500, new AuthResponse
                {
                    Success = false,
                    Message = "An unexpected error occurred while processing registration."
                });
            }
        }

        [HttpPost("login")]
        [EnableRateLimiting("strict-auth")]
        public async Task<ActionResult<AuthResponse>> Login(LoginRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email) || string.IsNullOrWhiteSpace(request?.Password))
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Email and password are required."
                    });
                }

                var normalizedEmail = request.Email.Trim().ToLowerInvariant();
                var lockoutKey = $"auth:lockout:{normalizedEmail}";
                var attemptsKey = $"auth:failed_attempts:{normalizedEmail}";

                // 1. Account Lockout Check
                var isLocked = await _cache.GetStringAsync(lockoutKey);
                if (!string.IsNullOrEmpty(isLocked))
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Account is temporarily locked due to multiple failed login attempts. Please try again after 15 minutes."
                    });
                }

                var user = await _context.Users.Include(u => u.University).FirstOrDefaultAsync(u => u.Email.ToLower() == normalizedEmail);

                // 2. Constant-time credential verification via PasswordHasherService
                bool isValidPassword = user != null && _passwordHasher.VerifyPassword(user.PasswordHash, request.Password);

                if (!isValidPassword)
                {
                    int currentAttempts = 1;
                    var attemptsStr = await _cache.GetStringAsync(attemptsKey);
                    if (int.TryParse(attemptsStr, out int parsedAttempts))
                    {
                        currentAttempts = parsedAttempts + 1;
                    }

                    if (currentAttempts >= 5)
                    {
                        await _cache.SetStringAsync(lockoutKey, "locked", new DistributedCacheEntryOptions
                        {
                            AbsoluteExpirationRelativeToNow = TimeSpan.FromMinutes(15)
                        });
                        await _cache.RemoveAsync(attemptsKey);

                        return BadRequest(new AuthResponse
                        {
                            Success = false,
                            Message = "Too many failed login attempts. Your account has been temporarily locked for 15 minutes."
                        });
                    }
                    else
                    {
                        await _cache.SetStringAsync(attemptsKey, currentAttempts.ToString(), new DistributedCacheEntryOptions
                        {
                            AbsoluteExpirationRelativeToNow = TimeSpan.FromMinutes(15)
                        });

                        int remaining = 5 - currentAttempts;
                        return Unauthorized(new AuthResponse
                        {
                            Success = false,
                            Message = $"Invalid credentials. You have {remaining} attempt(s) remaining before temporary lockout."
                        });
                    }
                }

                // Successful authentication: clear any failed attempts
                await _cache.RemoveAsync(attemptsKey);
                await _cache.RemoveAsync(lockoutKey);

                // Automatic hash upgrade: if legacy unsalted SHA-256, upgrade to salted PBKDF2 immediately
                if (_passwordHasher.NeedsRehash(user.PasswordHash))
                {
                    user.PasswordHash = _passwordHasher.HashPassword(request.Password);
                    user.UpdatedAt = DateTime.UtcNow;
                    _context.Users.Update(user);
                    await _context.SaveChangesAsync();
                }

                if (!user.IsApproved && user.UserType.ToLower() != "admin")
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Your account is pending approval by the coordinator."
                    });
                }

                if (!user.IsActive)
                {
                    return BadRequest(new AuthResponse
                    {
                        Success = false,
                        Message = "Your account is pending approval by the coordinator or has been deactivated."
                    });
                }

                var sessionId = Convert.ToHexString(RandomNumberGenerator.GetBytes(32));
                var permissions = await _permissionService.GetRolePermissionsAsync(user.UserType);

                var userDto = new UserDto
                {
                    Id = user.Id,
                    Name = user.Name,
                    Email = user.Email,
                    UserType = user.UserType,
                    UniversityId = user.UniversityId,
                    SubjectId1 = user.SubjectId1,
                    SubjectId2 = user.SubjectId2,
                    SubjectId3 = user.SubjectId3,
                    EmpId = user.EmpId,
                    Fname = user.Fname,
                    AadharNo = user.AadharNo,
                    PanNo = user.PanNo,
                    CollegeId = user.CollegeId,
                    Experience = user.Experience,
                    Phone = user.Phone,
                    Address = user.Address,
                    ProfileImage = user.ProfileImage,
                    IsActive = user.IsActive,
                    IsApproved = user.IsApproved,
                    UniversityName = user.University?.UniversityName,
                    Permissions = permissions
                };

                var sessionData = new UserSessionData
                {
                    Id = user.Id,
                    Name = user.Name,
                    Email = user.Email,
                    UserType = user.UserType,
                    UniversityId = user.UniversityId,
                    SubjectId1 = user.SubjectId1,
                    CollegeId = user.CollegeId,
                    Permissions = permissions
                };

                // Store session and user details in Redis Cache
                try
                {
                    var cacheOptions = new DistributedCacheEntryOptions
                    {
                        AbsoluteExpirationRelativeToNow = TimeSpan.FromHours(8)
                    };
                    await _cache.SetStringAsync($"session:{sessionId}", JsonSerializer.Serialize(sessionData, _jsonOptions), cacheOptions);
                    await _cache.SetStringAsync($"user_details_{user.Id}", JsonSerializer.Serialize(userDto, _jsonOptions), cacheOptions);
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "Failed to persist user session to cache on login.");
                    return StatusCode(503, new AuthResponse
                    {
                        Success = false,
                        Message = "Authentication service is temporarily unavailable. Please try again."
                    });
                }

                SetSessionCookie(sessionId);

                return Ok(new AuthResponse
                {
                    Success = true,
                    Message = "Login successful",
                    Token = sessionId,
                    User = userDto
                });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error processing AcceptInvitation");
                return StatusCode(500, new AuthResponse
                {
                    Success = false,
                    Message = "An unexpected error occurred while activating account."
                });
            }
        }

        [HttpGet("invitation-details")]
        public async Task<ActionResult<InvitationDetailsDto>> GetInvitationDetails([FromQuery] string token)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(token))
                {
                    return BadRequest(new { success = false, message = "Token is required" });
                }

                var invitation = _context.Invitations
                    .Include(i => i.University)
                    .Include(i => i.Department)
                    .FirstOrDefault(i => i.Token == token);

                if (invitation == null)
                {
                    return NotFound(new { success = false, message = "Invitation not found" });
                }

                if (invitation.IsUsed)
                {
                    return BadRequest(new { success = false, message = "Invitation has already been used" });
                }

                if (invitation.ExpiresAt < DateTime.UtcNow)
                {
                    return BadRequest(new { success = false, message = "Invitation has expired" });
                }

                return Ok(new InvitationDetailsDto
                {
                    Email = invitation.Email,
                    UniversityId = invitation.UniversityId,
                    UniversityName = invitation.University.UniversityName,
                    DepartmentId = invitation.DepartmentId,
                    DepartmentName = invitation.Department.Name,
                    UserType = invitation.UserType
                });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error in ChangePassword");
                return StatusCode(500, new { success = false, message = "An error occurred while changing password." });
            }
        }

