        private string HashPassword(string password)
        {
            return _passwordHasher.HashPassword(password);
        }

        private bool VerifyPassword(string password, string hash)
        {
            return _passwordHasher.VerifyPassword(hash, password);
        }

        // Bounded, thread-safe OTP Storage with expiration & attempt tracking (M4)
        private record OtpRecord(string Otp, DateTime Expiry, int Attempts = 0);
        private static readonly ConcurrentDictionary<string, OtpRecord> _emailOtps = new(StringComparer.OrdinalIgnoreCase);
        private static readonly ConcurrentDictionary<string, OtpRecord> _phoneOtps = new(StringComparer.OrdinalIgnoreCase);
        private static readonly ConcurrentDictionary<string, OtpRecord> _passwordResetOtps = new(StringComparer.OrdinalIgnoreCase);

        private static void SweepExpired(ConcurrentDictionary<string, OtpRecord> store)
        {
            var now = DateTime.UtcNow;
            foreach (var kv in store)
            {
                if (kv.Value.Expiry < now)
                {
                    store.TryRemove(kv.Key, out _);
                }
            }
        }

        [HttpPost("send-email-otp")]
        public async Task<ActionResult> SendEmailOtp([FromBody] SendOtpRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email))
                {
                    return BadRequest(new { success = false, message = "Email is required" });
                }

                SweepExpired(_emailOtps);
                var normalizedEmail = request.Email.Trim().ToLower();

                // If email already exists, return uniform success response to prevent user enumeration (M2)
                if (await _context.Users.AnyAsync(u => u.Email.ToLower() == normalizedEmail))
                {
                    return Ok(new { success = true, message = "OTP sent to email successfully" });
                }

                var otp = RandomNumberGenerator.GetInt32(100000, 1000000).ToString();
                var expiry = DateTime.UtcNow.AddMinutes(10);

                _emailOtps[normalizedEmail] = new OtpRecord(otp, expiry, 0);

                try
                {
                    await _emailService.SendOtpEmailAsync(normalizedEmail, otp);
                }
                catch (Exception ex)
                {
                    _logger.LogError(ex, "Failed to send OTP email to {Email}", normalizedEmail);
                    return StatusCode(500, new { success = false, message = "Failed to send OTP email" });
                }

                return Ok(new { success = true, message = "OTP sent to email successfully" });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error in SendEmailOtp");
                return StatusCode(500, new { success = false, message = "An error occurred while sending OTP." });
            }
        }

        [HttpPost("verify-email-otp")]
        public ActionResult VerifyEmailOtp([FromBody] VerifyOtpRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email) || string.IsNullOrWhiteSpace(request?.Otp))
                {
                    return BadRequest(new { success = false, message = "Email and OTP are required" });
                }

                var normalizedEmail = request.Email.Trim().ToLower();

                if (!_emailOtps.TryGetValue(normalizedEmail, out var record))
                {
                    return BadRequest(new { success = false, message = "Invalid or expired OTP" });
                }

                if (DateTime.UtcNow > record.Expiry || record.Attempts >= 5)
                {
                    _emailOtps.TryRemove(normalizedEmail, out _);
                    return BadRequest(new { success = false, message = "OTP has expired or exceeded maximum verification attempts" });
                }

                if (!_passwordHasher.FixedTimeEquals(record.Otp, request.Otp.Trim()))
                {
                    _emailOtps[normalizedEmail] = record with { Attempts = record.Attempts + 1 };
                    return BadRequest(new { success = false, message = "Invalid OTP" });
                }

                _emailOtps.TryRemove(normalizedEmail, out _);
                return Ok(new { success = true, message = "Email verified successfully" });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error in VerifyEmailOtp");
                return StatusCode(500, new { success = false, message = "An error occurred while verifying OTP." });
            }
        }

