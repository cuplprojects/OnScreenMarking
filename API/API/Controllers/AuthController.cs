        [HttpPost("logout")]
        public async Task<IActionResult> Logout()
        {
            try
            {
                string? sessionId = Request.Cookies[RedisSessionAuthenticationHandler.CookieName];
                if (string.IsNullOrWhiteSpace(sessionId))
                {
                    sessionId = User.FindFirst("sessionId")?.Value;
                }

                if (string.IsNullOrWhiteSpace(sessionId) && Request.Headers.TryGetValue(RedisSessionAuthenticationHandler.HeaderName, out var hVal))
                {
                    sessionId = hVal.FirstOrDefault();
                }

                if (!string.IsNullOrWhiteSpace(sessionId))
                {
                    try
                    {
                        await _cache.RemoveAsync($"session:{sessionId}");
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"[Redis Cache] Error clearing session on logout: {ex.Message}");
                    }
                }

                var userIdStr = User.FindFirst("id")?.Value;
                if (!string.IsNullOrEmpty(userIdStr) && int.TryParse(userIdStr, out int userId))
                {
                    try
                    {
                        await _cache.RemoveAsync($"user_details_{userId}");
                    }
                    catch (Exception ex)
                    {
                        Console.WriteLine($"[Redis Cache] Failed to clear cache on logout for user {userId}: {ex.Message}");
                    }
                }

                ClearSessionCookie();

                return Ok(new { success = true, message = "Logged out successfully" });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [HttpPost("forgot-password")]
        public async Task<ActionResult> ForgotPassword([FromBody] ForgotPasswordRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email))
                {
                    return BadRequest(new { success = false, message = "Email is required" });
                }

                var normalizedEmail = request.Email.Trim().ToLower();
                var user = await _context.Users.FirstOrDefaultAsync(u => u.Email.ToLower() == normalizedEmail);
                if (user == null)
                {
                    return BadRequest(new { success = false, message = "No account found registered with this email address." });
                }

                var otp = new Random().Next(100000, 999999).ToString();
                var expiry = DateTime.UtcNow.AddMinutes(15);

                // Store in memory
                _passwordResetOtps[normalizedEmail] = (otp, expiry);

                // Store in Redis
                try
                {
                    var cacheOptions = new DistributedCacheEntryOptions
                    {
                        AbsoluteExpirationRelativeToNow = TimeSpan.FromMinutes(15)
                    };
                    await _cache.SetStringAsync($"pwd_reset_otp_{normalizedEmail}", otp, cacheOptions);
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[Redis Cache] Could not cache password reset OTP in Redis: {ex.Message}");
                }

                // Send OTP via Email
                try
                {
                    await _emailService.SendPasswordResetOtpAsync(user.Email, user.Name ?? "User", otp);
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"Failed to send password reset email: {ex.Message}");
                    return StatusCode(500, new { success = false, message = "Failed to send verification email. Please check SMTP settings or try again." });
                }

                return Ok(new { success = true, message = "Password reset verification code has been sent to your email." });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [HttpPost("verify-reset-otp")]
        public async Task<ActionResult> VerifyResetOtp([FromBody] VerifyResetOtpRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email) || string.IsNullOrWhiteSpace(request?.Otp))
                {
                    return BadRequest(new { success = false, message = "Email and verification code are required" });
                }

                var normalizedEmail = request.Email.Trim().ToLower();
                string? storedOtp = null;

                // Try Redis first
                try
                {
                    storedOtp = await _cache.GetStringAsync($"pwd_reset_otp_{normalizedEmail}");
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[Redis Cache] Error checking reset OTP in Redis: {ex.Message}");
                }

                if (string.IsNullOrEmpty(storedOtp) && _passwordResetOtps.TryGetValue(normalizedEmail, out var memData))
                {
                    if (memData.Expiry >= DateTime.UtcNow)
                    {
                        storedOtp = memData.Otp;
                    }
                    else
                    {
                        _passwordResetOtps.Remove(normalizedEmail);
                    }
                }

                if (string.IsNullOrEmpty(storedOtp) || storedOtp != request.Otp.Trim())
                {
                    return BadRequest(new { success = false, message = "Invalid or expired verification code." });
                }

                return Ok(new { success = true, message = "Verification code confirmed." });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [HttpPost("reset-password")]
        public async Task<ActionResult> ResetPassword([FromBody] ResetPasswordRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.Email) || string.IsNullOrWhiteSpace(request?.Otp) || string.IsNullOrWhiteSpace(request?.NewPassword))
                {
                    return BadRequest(new { success = false, message = "Email, verification code and new password are required." });
                }

                if (request.NewPassword.Length < 6)
                {
                    return BadRequest(new { success = false, message = "Password must be at least 6 characters long." });
                }

                var normalizedEmail = request.Email.Trim().ToLower();
                string? storedOtp = null;

                try
                {
                    storedOtp = await _cache.GetStringAsync($"pwd_reset_otp_{normalizedEmail}");
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[Redis Cache] Error checking reset OTP in Redis: {ex.Message}");
                }

                if (string.IsNullOrEmpty(storedOtp) && _passwordResetOtps.TryGetValue(normalizedEmail, out var memData))
                {
                    if (memData.Expiry >= DateTime.UtcNow)
                    {
                        storedOtp = memData.Otp;
                    }
                    else
                    {
                        _passwordResetOtps.Remove(normalizedEmail);
                    }
                }

                if (string.IsNullOrEmpty(storedOtp) || storedOtp != request.Otp.Trim())
                {
                    return BadRequest(new { success = false, message = "Invalid or expired verification code." });
                }

                var user = await _context.Users.FirstOrDefaultAsync(u => u.Email.ToLower() == normalizedEmail);
                if (user == null)
                {
                    return NotFound(new { success = false, message = "User not found." });
                }

                user.PasswordHash = HashPassword(request.NewPassword);
                user.UpdatedAt = DateTime.UtcNow;

                _context.Users.Update(user);
                await _context.SaveChangesAsync();

                // Clear OTP
                _passwordResetOtps.Remove(normalizedEmail);
                try
                {
                    await _cache.RemoveAsync($"pwd_reset_otp_{normalizedEmail}");
                    await _cache.RemoveAsync($"user_details_{user.Id}");
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[Redis Cache] Cleanup error: {ex.Message}");
                }

                return Ok(new { success = true, message = "Password reset successfully. You can now log in with your new password." });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }

        [Authorize]
        [HttpPost("change-password")]
        public async Task<ActionResult> ChangePassword([FromBody] ChangePasswordRequest request)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(request?.CurrentPassword) || string.IsNullOrWhiteSpace(request?.NewPassword))
                {
                    return BadRequest(new { success = false, message = "Current password and new password are required." });
                }

                if (request.NewPassword.Length < 6)
                {
                    return BadRequest(new { success = false, message = "New password must be at least 6 characters long." });
                }

                var userIdStr = User.FindFirst("id")?.Value;
                if (string.IsNullOrEmpty(userIdStr) || !int.TryParse(userIdStr, out int userId))
                {
                    return Unauthorized(new { success = false, message = "Invalid user identity session." });
                }

                var user = await _context.Users.FindAsync(userId);
                if (user == null)
                {
                    return NotFound(new { success = false, message = "User not found." });
                }

                if (!VerifyPassword(request.CurrentPassword, user.PasswordHash))
                {
                    return BadRequest(new { success = false, message = "Current password is incorrect." });
                }

                if (request.CurrentPassword == request.NewPassword)
                {
                    return BadRequest(new { success = false, message = "New password must be different from your current password." });
                }

                user.PasswordHash = HashPassword(request.NewPassword);
                user.UpdatedAt = DateTime.UtcNow;

                _context.Users.Update(user);
                await _context.SaveChangesAsync();

                // Invalidate user cache in Redis
                try
                {
                    await _cache.RemoveAsync($"user_details_{user.Id}");
                }
                catch (Exception ex)
                {
                    Console.WriteLine($"[Redis Cache] Cleanup error on change password: {ex.Message}");
                }

                return Ok(new { success = true, message = "Password changed successfully." });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { success = false, message = ex.Message });
            }
        }
