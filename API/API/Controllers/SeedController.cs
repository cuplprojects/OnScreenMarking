                            questions.Add(new Question
                            {
                                SectionId = secB.Id,
                                QuestionNo = qNo.ToString(),
                                Marks = 6.0m,
                                TypeId = saType.QuestionTypeId,
                                Type = saType.QuestionTypeName,
                                IsOptional = false,
                                CreatedAt = DateTime.UtcNow
                            });
                        }
                        for (int qNo = 16; qNo <= 20; qNo++)
                        {
                            questions.Add(new Question
                            {
                                SectionId = secC.Id,
                                QuestionNo = qNo.ToString(),
                                Marks = 10.0m,
                                TypeId = laType.QuestionTypeId,
                                Type = laType.QuestionTypeName,
                                IsOptional = qNo > 18,
                                OptionalGroupCode = qNo > 18 ? "G1" : null,
                                CreatedAt = DateTime.UtcNow
                            });
                        }
                        _context.Questions.AddRange(questions);
                        await _context.SaveChangesAsync();

                        papers.Add(p);
                    }
                    else
                    {
                        papers.Add(existing);
                    }
                }

                // 7. Ensure Academic Session & Project
                var session = await _context.Sessions.FirstOrDefaultAsync(s => s.SessionName == "Academic Session 2026-2027");
                if (session == null)
                {
                    session = new Session { SessionName = "Academic Session 2026-2027", IsActive = true };
                    _context.Sessions.Add(session);
                    await _context.SaveChangesAsync();
                }

                var project = await _context.Projects.FirstOrDefaultAsync(p => p.ProjectName == "End Semester Examination Nov 2026" && p.UniversityId == uniId);
                if (project == null)
                {
                    project = new Project
                    {
                        ProjectName = "End Semester Examination Nov 2026",
                        SessionId = session.SessionId,
                        UniversityId = uniId,
                        IsActive = true,
                        CreatedAt = DateTime.UtcNow
                    };
                    _context.Projects.Add(project);
                    await _context.SaveChangesAsync();
                }

                // 8. Find or create examiners
                var examiners = await _context.Users.Where(u => u.UserType == "examiner" && u.IsActive).ToListAsync();
                if (examiners.Count < 5)
                {
                    var newExaminers = new[]
                    {
                        ("Dr. Rajesh Sharma", "sharma.rajesh@osm.com"),
                        ("Prof. Priya Verma", "verma.priya@osm.com"),
                        ("Dr. Amit Gupta", "gupta.amit@osm.com"),
                        ("Prof. Sunita Singh", "singh.sunita@osm.com"),
                        ("Dr. Vikram Patel", "patel.vikram@osm.com")
                    };
                    foreach (var (exName, exEmail) in newExaminers)
                    {
                        if (!examiners.Any(e => e.Email == exEmail))
                        {
                            var ex = new User
                            {
                                Name = exName,
                                Email = exEmail,
                                PasswordHash = HashPassword("Examiner@123"),
                                AutoGeneratedPassword = "Examiner@123",
                                UserType = "examiner",
                                UniversityId = uniId,
                                IsActive = true,
                                IsApproved = true,
                                Phone = "+91-9876500000",
                                Address = "Examiner Evaluation Faculty"
                            };
                            _context.Users.Add(ex);
                            await _context.SaveChangesAsync();
                            examiners.Add(ex);
                        }
                    }
                }

                // 9. Enter Project: Import/Add 10 Papers, Sections, and Assign Evaluators
                int importedPapersCount = 0;
                int configuredSectionsCount = 0;
                int assignedExaminersCount = 0;

                foreach (var paper in papers)
                {
                    var projectPaper = await _context.ProjectPapers
                        .Include(pp => pp.ProjectPaperSections)
                        .Include(pp => pp.PaperExaminers)
                        .FirstOrDefaultAsync(pp => pp.ProjectId == project.ProjectId && pp.PaperId == paper.PaperId);

                    if (projectPaper == null)
                    {
                        projectPaper = new ProjectPaper
                        {
                            ProjectId = project.ProjectId,
                            PaperId = paper.PaperId,
                            CatchNo = $"CATCH-{paper.PaperNumber:D3}",
                            IsActive = true,
                            IsSectionConfigured = true,
                            IsExaminerAssigned = true,
                            CreatedAt = DateTime.UtcNow,
                            UpdatedAt = DateTime.UtcNow
                        };
                        _context.ProjectPapers.Add(projectPaper);
                        await _context.SaveChangesAsync();
                        importedPapersCount++;
                    }

                    // Import/Configure ProjectPaperSections if none exist
                    if (!projectPaper.ProjectPaperSections.Any())
                    {
                        var ppsA = new ProjectPaperSection
                        {
                            ProjectPaperId = projectPaper.Id,
                            BatchId = 1,
                            Name = "Section A",
                            Description = "Multiple Choice Questions",
                            TotalQuestions = 10,
                            TotalMarks = 20.0m,
                            StartQuestion = 1,
                            EndQuestion = 10,
                            MaxQuestionsToAttempt = 10,
                            CreatedAt = DateTime.UtcNow,
                            UpdatedAt = DateTime.UtcNow
                        };
                        var ppsB = new ProjectPaperSection
                        {
                            ProjectPaperId = projectPaper.Id,
                            BatchId = 1,
                            Name = "Section B",
                            Description = "Short Answer Questions",
                            TotalQuestions = 5,
                            TotalMarks = 30.0m,
                            StartQuestion = 11,
                            EndQuestion = 15,
                            MaxQuestionsToAttempt = 5,
                            CreatedAt = DateTime.UtcNow,
                            UpdatedAt = DateTime.UtcNow
                        };
                        var ppsC = new ProjectPaperSection
                        {
                            ProjectPaperId = projectPaper.Id,
                            BatchId = 1,
                            Name = "Section C",
                            Description = "Long Answer Questions",
                            TotalQuestions = 5,
                            TotalMarks = 50.0m,
                            StartQuestion = 16,
                            EndQuestion = 20,
                            MaxQuestionsToAttempt = 3,
                            CreatedAt = DateTime.UtcNow,
                            UpdatedAt = DateTime.UtcNow
                        };
                        _context.ProjectPaperSections.AddRange(new[] { ppsA, ppsB, ppsC });
                        await _context.SaveChangesAsync();

                        var ppsQuestions = new List<Question>();
                        for (int qNo = 1; qNo <= 10; qNo++)
                        {
                            ppsQuestions.Add(new Question
                            {
                                ProjectPaperSectionId = ppsA.Id,
                                QuestionNo = qNo.ToString(),
                                Marks = 2.0m,
                                TypeId = mcqType.QuestionTypeId,
                                Type = mcqType.QuestionTypeName,
                                IsOptional = false,
                                CreatedAt = DateTime.UtcNow
                            });
                        }
                        for (int qNo = 11; qNo <= 15; qNo++)
                        {
                            ppsQuestions.Add(new Question
                            {
                                ProjectPaperSectionId = ppsB.Id,
                                QuestionNo = qNo.ToString(),
                                Marks = 6.0m,
                                TypeId = saType.QuestionTypeId,
                                Type = saType.QuestionTypeName,
                                IsOptional = false,
                                CreatedAt = DateTime.UtcNow
                            });
                        }
                        for (int qNo = 16; qNo <= 20; qNo++)
                        {
                            ppsQuestions.Add(new Question
                            {
                                ProjectPaperSectionId = ppsC.Id,
                                QuestionNo = qNo.ToString(),
                                Marks = 10.0m,
                                TypeId = laType.QuestionTypeId,
                                Type = laType.QuestionTypeName,
                                IsOptional = qNo > 18,
                                OptionalGroupCode = qNo > 18 ? "G1" : null,
                                CreatedAt = DateTime.UtcNow
                            });
                        }
                        _context.Questions.AddRange(ppsQuestions);
                        await _context.SaveChangesAsync();
                        configuredSectionsCount += 3;
                    }

                    // Assign Evaluators / Examiners to ProjectPaper
                    if (!projectPaper.PaperExaminers.Any() && examiners.Any())
                    {
                        var assignedToPaper = examiners.Take(2).ToList();
                        foreach (var ex in assignedToPaper)
                        {
                            _context.PaperExaminers.Add(new PaperExaminer
                            {
                                ProjectPaperId = projectPaper.Id,
                                ExaminerId = ex.Id,
                                ProjectId = project.ProjectId,
                                IsActive = true,
                                AssignedAt = DateTime.UtcNow
                            });
                            assignedExaminersCount++;
                        }
                        projectPaper.IsExaminerAssigned = true;
                        projectPaper.IsSectionConfigured = true;
                        await _context.SaveChangesAsync();
                    }
                }

                return Ok(new
                {
                    Success = true,
                    Message = "Academic workflow fully seeded with 10 entries in each category!",
                    Coordinator = new { coordinator.Email, Password = "Coordinator@123", UniversityName = uni.UniversityName },
                    DepartmentsCount = departments.Count,
                    CoursesCount = courses.Count,
                    SectionMastersCount = sectionMasters.Count,
                    MasterPapersCount = papers.Count,
                    Project = new { project.ProjectId, project.ProjectName },
                    ProjectPapersCount = papers.Count,
                    TotalSectionsConfigured = configuredSectionsCount,
                    TotalExaminerAssignments = assignedExaminersCount
                });
            }
            catch (Exception ex)
            {
                return StatusCode(500, new { Success = false, Message = ex.Message, Inner = ex.InnerException?.Message });
            }
        }

    }
