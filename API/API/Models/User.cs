using System;
using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Text.Json.Serialization;

namespace API.Models
{
    public class User
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
        public int Id { get; set; }
        public string Name { get; set; }
        [EmailAddress]
        public string Email { get; set; }
        [JsonIgnore]
        public string PasswordHash { get; set; }
        public string UserType { get; set; } // examiner, coordinator, admin
        public bool IsActive { get; set; } = true;
        public bool IsApproved { get; set; } = false;
        public string ProfileImage { get; set; }
        public string Phone { get; set; }
        public string Address { get; set; }
        public int? UniversityId { get; set; }
        public University University { get; set; }
        public int? SubjectId1 { get; set; }
        public int? SubjectId2 { get; set; }
        public int? SubjectId3 { get; set; }
        public int? EmpId { get; set; }
        public string? Fname { get; set; } = "";
        public string? AadharNo { get; set; } = "";
        public string? PanNo { get; set; } = "";
        public int? CollegeId { get; set; }
        public string? Experience { get; set; } = "";
        [JsonIgnore]
        public string AutoGeneratedPassword { get; set; }
        public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
        public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
        
        // Navigation properties
        [NotMapped]
        public ICollection<ExaminerExpertise> Expertise { get; set; } = new List<ExaminerExpertise>();
        public ICollection<Allocation> Allocations { get; set; } = new List<Allocation>();
        public ICollection<Marking> Markings { get; set; } = new List<Marking>();
    }
}
